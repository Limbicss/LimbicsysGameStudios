#!/usr/bin/env python3
"""port/convert.py - port the Claude Code studio (.claude/) to Codex and Antigravity (AGY).

Reads the originals, never writes to .claude/. Safe to rerun after an upstream update.

  python3 port/convert.py            generate everything
  python3 port/convert.py --check   generate nothing; verify counts + no Claude-only syntax left (exit 1 on failure)
  python3 port/convert.py --prune   also delete generated files whose source disappeared

Outputs (all carry the GENERATED marker, edit the source and rerun instead):
  .agents/skills/<name>/...      74 skills   -> shared: Codex ($name) and AGY (/name) both scan .agents/skills
  .codex/agents/<name>.toml      49 agents   -> Codex custom agents
  .agents/agents/<name>.md       49 agents   -> AGY custom subagents
  .agents/rules/<name>.md        14 rules    -> AGY rules (trigger: glob)
  AGENTS.md                      index       -> read by both (template: port/templates/AGENTS.md.tmpl)
Python 3.8+, stdlib only.
"""
import argparse, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".claude"
MARK = "GENERATED by port/convert.py from .claude/ - edit the source and rerun; manual edits are overwritten"
EXPECT = {"agents": 49, "skills": 74}

# ---------------------------------------------------------------- parsing
def split_frontmatter(text):
    m = re.match(r"\A---\n(.*?)\n---\n?(.*)\Z", text, re.S)
    if not m:
        return {}, text
    fm = {}
    for line in m.group(1).split("\n"):
        k = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if not k:
            continue
        v = k.group(2).strip()
        if v.startswith('"') and v.endswith('"') and len(v) >= 2:
            try:
                v = json.loads(v)
            except ValueError:
                v = v[1:-1]
        elif v.startswith("[") and v.endswith("]"):
            v = [x.strip() for x in v[1:-1].split(",") if x.strip()]
        fm[k.group(1)] = v
    return fm, m.group(2)

def csv(v):
    if isinstance(v, list):
        return v
    return [x.strip() for x in str(v or "").split(",") if x.strip()]

# ---------------------------------------------------------------- text transform
WORD = {"Read": "file read", "Glob": "file search", "Grep": "text search", "Write": "file write",
        "Edit": "file edit", "Bash": "shell", "PowerShell": "shell", "WebSearch": "web search",
        "WebFetch": "web fetch", "Agent": "subagent", "Task": "subagent"}
KEEP_SOURCE_PATHS = {"skill-test", "skill-improve"}   # these audit the Claude-format originals

def fix_cmd(cmd, skill):
    cmd = cmd.replace("${CLAUDE_SKILL_DIR}/../../", ".claude/")
    cmd = cmd.replace("${CLAUDE_SKILL_DIR}", ".agents/skills/%s" % skill)
    cmd = cmd.replace("${CLAUDE_PROJECT_DIR}/", "").replace("$CLAUDE_PROJECT_DIR/", "")
    return cmd

def xform(text, owner, skills):
    # !`cmd` lines are executed by Claude before the skill reads them. Elsewhere the agent runs them.
    def bang(m):
        return "**Run first** (shell, repo root) and use its output as-is: `%s`" % fix_cmd(m.group(1), owner)
    text = re.sub(r"^!`(.+)`[ \t]*$", bang, text, flags=re.M)
    text = text.replace("Resolved above;", "Resolved by the command above;")
    text = fix_cmd(text, owner)
    text = re.sub(r"`\$ARGUMENTS`|\$ARGUMENTS", "the user's arguments", text)
    text = re.sub(r"`AskUserQuestion`|\bAskUserQuestion\b", "ask-the-user step", text)
    text = re.sub(r"`subagent_type: ([\w-]+)`", r"agent `\1`", text)
    text = re.sub(r"subagent_type:\s*", "agent: ", text)
    text = re.sub(r"`(TaskCreate|TaskGet|TaskList|TaskUpdate|TodoWrite)`|\b(TaskCreate|TaskGet|TaskList|TaskUpdate|TodoWrite)\b", "task list", text)
    text = re.sub(r"`(%s)`" % "|".join(WORD), lambda m: WORD[m.group(1)], text)
    if owner not in KEEP_SOURCE_PATHS:
        text = re.sub(r"\.claude/skills/([\w-]+)/", lambda m: ".agents/skills/%s/" % m.group(1) if m.group(1) in skills else m.group(0), text)
        text = re.sub(r"\.claude/rules/", ".agents/rules/", text)
        text = re.sub(r"\.claude/agents/([\w-]+)\.md", r".agents/agents/\1.md", text)
    text = re.sub(r"\.claude/settings(\.local)?\.json", ".codex/hooks.json and .agents/hooks.json", text)
    text = text.replace("Claude Code", "the agent runtime").replace("Claude", "the agent")
    return text

# ---------------------------------------------------------------- toml / yaml helpers
def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'

def toml_multiline(s):
    if "'''" not in s:
        return "'''\n" + s + "'''"
    return '"""\n' + s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'

def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)

def expand_braces(p):
    m = re.search(r"\{([^{}]+)\}", p)
    if not m:
        return [p]
    out = []
    for alt in m.group(1).split(","):
        out += expand_braces(p[:m.start()] + alt + p[m.end():])
    return out

# ---------------------------------------------------------------- generators
def write(path, content, produced):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    produced.add(path.resolve())

def gen_skills(skills, produced):
    n = 0
    for d in sorted((SRC / "skills").iterdir()):
        if not (d / "SKILL.md").is_file():
            continue
        name = d.name
        fm, body = split_frontmatter((d / "SKILL.md").read_text(encoding="utf-8"))
        hint = fm.get("argument-hint", "")
        head = "---\nname: %s\ndescription: %s\n---\n<!-- %s -->\n" % (name, yaml_str(fm.get("description", name)), MARK)
        note = "> Portable skill `%s` - call it as `$%s` (Codex) or `/%s` (Antigravity). Arguments = what the user typed after the name%s. Terms: see AGENTS.md \"Portable terms\".\n" % (
            name, name, name, (" (hint: `%s`)" % hint) if hint else "")
        write(d.parent.parent.parent / ".agents" / "skills" / name / "SKILL.md",
              head + note + xform(body, name, skills), produced)
        for f in sorted(d.rglob("*")):
            if f.is_file() and f.name != "SKILL.md":
                rel = f.relative_to(d)
                out = ROOT / ".agents" / "skills" / name / rel
                if f.suffix == ".md":
                    t = f.read_text(encoding="utf-8")
                    write(out, "<!-- %s -->\n" % MARK + xform(t, name, skills), produced)
                else:
                    out.parent.mkdir(parents=True, exist_ok=True); out.write_bytes(f.read_bytes()); produced.add(out.resolve())
        n += 1
    return n

EFFORT = {"opus": "high", "sonnet": "medium", "haiku": "low"}
AGY_MODEL = {"opus": "pro", "haiku": "flash"}

def agent_preamble(fm):
    tools = [WORD.get(t.split("(")[0], t) for t in csv(fm.get("tools"))]
    deny = [WORD.get(t.split("(")[0], t) for t in csv(fm.get("disallowedTools"))]
    lines = ["Runtime note (ported from the original .claude/agents definition): per-agent tool limits are not enforced here, so treat them as binding rules."]
    if tools:
        lines.append("Tools you may use: %s." % ", ".join(dict.fromkeys(tools)))
    if deny:
        lines.append("Tools you must NOT use: %s." % ", ".join(dict.fromkeys(deny)))
    if fm.get("skills"):
        lines.append("Skills you should reach for: %s." % ", ".join(csv(fm["skills"])))
    if fm.get("memory"):
        lines.append("Keep persistent notes as described in .agents/rules/agent-memory.md.")
    if fm.get("isolation"):
        lines.append("Work in an isolated branch/worktree (%s) and report back; do not touch the main checkout." % fm["isolation"])
    lines.append("Source model tier: %s (see .claude/docs/model-tiers.md)." % fm.get("model", "inherit"))
    return "\n".join(lines) + "\n\n"

def gen_agents(skills, produced):
    n = 0
    for f in sorted((SRC / "agents").glob("*.md")):
        fm, body = split_frontmatter(f.read_text(encoding="utf-8"))
        name = fm.get("name", f.stem)
        desc = fm.get("description", name)
        text = agent_preamble(fm) + xform(body.lstrip("\n"), name, skills)
        # Codex: standalone TOML, required name/description/developer_instructions
        t = "# %s\nname = %s\ndescription = %s\n" % (MARK, toml_str(name), toml_str(desc))
        if fm.get("model") in EFFORT:
            t += "model_reasoning_effort = %s\n" % toml_str(EFFORT[fm["model"]])
        t += "developer_instructions = %s\n" % toml_multiline(text)
        write(ROOT / ".codex" / "agents" / (name + ".toml"), t, produced)
        # AGY: markdown + frontmatter; tools omitted on purpose (an unmapped tool name can hang the subagent)
        y = "---\nname: %s\ndescription: %s\nmodel: %s\n" % (name, yaml_str(desc), AGY_MODEL.get(fm.get("model"), "inherit"))
        if "Bash" not in csv(fm.get("tools")):
            y += "commandExecutionPolicy: off\n"
        y += "---\n<!-- %s -->\n" % MARK
        write(ROOT / ".agents" / "agents" / (name + ".md"), y + text, produced)
        n += 1
    return n

def gen_rules(skills, produced):
    n, table = 0, []
    for f in sorted((SRC / "rules").glob("*.md")):
        raw = f.read_text(encoding="utf-8")
        m = re.match(r"\A---\n(.*?)\n---\n?(.*)\Z", raw, re.S)
        paths = re.findall(r'^\s*-\s*"([^"]+)"', m.group(1), re.M) if m else []
        body = m.group(2) if m else raw
        globs = []
        for p in paths:
            globs += expand_braces(p)
        fmtxt = "---\ntrigger: glob\ndescription: %s\nglobs: %s\n---\n" % (yaml_str("Path-scoped rule: " + f.stem), yaml_str(", ".join(globs)))
        write(ROOT / ".agents" / "rules" / f.name, fmtxt + "<!-- %s -->\n" % MARK + xform(body, f.stem, skills), produced)
        table.append((f.name, paths))
        n += 1
    return n, table

def gen_agents_md(table, produced):
    tmpl = (ROOT / "port" / "templates" / "AGENTS.md.tmpl").read_text(encoding="utf-8")
    # roster from .claude/docs/agent-roster.md : tier heading -> agent names
    tiers, cur = [], None
    for line in (SRC / "docs" / "agent-roster.md").read_text(encoding="utf-8").splitlines():
        h = re.match(r"^#{2,3} (.+)$", line)
        if h:
            cur = [h.group(1).strip(), []]; tiers.append(cur); continue
        r = re.match(r"^\| `([\w-]+)` \|", line)
        if r and cur is not None:
            cur[1].append(r.group(1))
    roster = "\n".join("- **%s**: %s" % (t, ", ".join("`%s`" % a for a in names)) for t, names in tiers if names)
    rules = "\n".join("| `.agents/rules/%s` | %s |" % (fn, " ; ".join("`%s`" % p for p in ps)) for fn, ps in table)
    out = tmpl.replace("{{ROSTER_COUNT}}", str(sum(len(n) for _, n in tiers))).replace("{{ROSTER}}", roster).replace("{{RULES_TABLE}}", rules)
    write(ROOT / "AGENTS.md", out, produced)

# ---------------------------------------------------------------- check
BAD = [
    (r"^!`", "bang-command injection"),
    (r"\$\{?CLAUDE_", "CLAUDE_* env var"),
    (r"AskUserQuestion|TaskCreate|TaskUpdate|TaskGet|TaskList|ExitPlanMode|TodoWrite|subagent_type", "Claude tool name"),
    (r"^(allowed-tools|user-invocable|argument-hint|disallowedTools|maxTurns)\s*:", "Claude frontmatter key"),
    (r"\.claude/settings", "Claude settings reference"),
    (r"@\.claude/", "Claude @-import"),
    (r"\bClaude\b", "the word Claude (the CLAUDE.md filename is allowed)"),
]

def table_rules():
    return [(p.name, None) for p in sorted((ROOT / ".agents" / "rules").glob("*.md"))]

def check():
    errs = []
    sk = [p for p in (ROOT / ".agents" / "skills").glob("*/SKILL.md")]
    cx = list((ROOT / ".codex" / "agents").glob("*.toml"))
    ag = list((ROOT / ".agents" / "agents").glob("*.md"))
    src_sk = [p for p in (SRC / "skills").glob("*/SKILL.md")]
    src_ag = list((SRC / "agents").glob("*.md"))
    print("skills  : source %d  ported %d  (expected %d)" % (len(src_sk), len(sk), EXPECT["skills"]))
    print("agents  : source %d  codex %d  agy %d  (expected %d)" % (len(src_ag), len(cx), len(ag), EXPECT["agents"]))
    if not (len(src_sk) == len(sk) == EXPECT["skills"]): errs.append("skill count")
    if not (len(src_ag) == len(cx) == len(ag) == EXPECT["agents"]): errs.append("agent count")
    try:
        import tomllib
        for p in cx:
            d = tomllib.loads(p.read_text(encoding="utf-8"))
            for k in ("name", "description", "developer_instructions"):
                if not d.get(k): errs.append("%s missing %s" % (p.name, k))
    except ImportError:
        print("note: python < 3.11, TOML parse check skipped")
    for p in sk + cx + ag + list((ROOT / ".agents" / "rules").glob("*.md")) + [ROOT / "AGENTS.md"]:
        for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            if "KEEP_SOURCE" in line: continue
            for rx, why in BAD:
                if re.search(rx, line.replace("CLAUDE.md", "")):
                    errs.append("%s:%d %s" % (p.relative_to(ROOT), i, why))
    rules = list((ROOT / ".agents" / "rules").glob("*.md"))
    print("rules   : %d AGY rules (trigger: glob)" % len(rules))
    # T4: Unity path rules + run-and-observe rule + default rigor
    for r in rules:
        t = r.read_text(encoding="utf-8")
        if not re.match(r"\A---\ntrigger: glob\n.*?globs: \".+\"\n---\n", t, re.S) or len(t.encode()) > 24000:
            errs.append("AGY rule frontmatter/size: %s" % r.name)
    unity = {"gameplay-code.md": "Assets/**/Gameplay/**/*.cs", "test-standards.md": "Assets/Tests/**/*.cs",
             "data-files.md": "Assets/**/Data/**/*.json", "ui-code.md": "Assets/**/UI/**/*.cs"}
    for fn, g in unity.items():
        p = ROOT / ".agents" / "rules" / fn
        if not p.is_file() or g not in p.read_text(encoding="utf-8"):
            errs.append("Unity glob missing in %s: %s" % (fn, g))
    am = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    if "RUN-AND-OBSERVE RULE" not in am or "production/qa/evidence" not in am: errs.append("run-and-observe rule not in AGENTS.md")
    for fn, _ in table_rules():
        if ".agents/rules/" + fn not in am: errs.append("rule not routed in AGENTS.md: " + fn)
    if not re.search(r"^modes:\s*\n\s+rigor: minimal", (ROOT / "project.yaml").read_text(encoding="utf-8"), re.M):
        errs.append("project.yaml modes.rigor: minimal missing")
    sz = (ROOT / "AGENTS.md").stat().st_size
    print("AGENTS.md: %d bytes (Codex limit 65536 set in .codex/config.toml; AGY limit 24000/file)" % sz)
    if sz > 24000: errs.append("AGENTS.md > 24000 bytes (AGY per-file limit)")
    for e in errs[:40]: print("FAIL", e)
    print("CHECK", "FAILED (%d)" % len(errs) if errs else "OK")
    return not errs

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--prune", action="store_true")
    a = ap.parse_args()
    if a.check:
        sys.exit(0 if check() else 1)
    produced = set()
    skills = {d.name for d in (SRC / "skills").iterdir() if (d / "SKILL.md").is_file()}
    ns = gen_skills(skills, produced)
    na = gen_agents(skills, produced)
    nr, table = gen_rules(skills, produced)
    gen_agents_md(table, produced)
    if a.prune:
        for root in (ROOT / ".agents", ROOT / ".codex" / "agents"):
            for f in root.rglob("*"):
                if f.is_file() and f.resolve() not in produced and MARK in f.read_text(encoding="utf-8", errors="ignore")[:600]:
                    f.unlink(); print("pruned", f.relative_to(ROOT))
    print("generated: %d skills, %d agents x2 targets, %d rules, AGENTS.md" % (ns, na, nr))

if __name__ == "__main__":
    main()
